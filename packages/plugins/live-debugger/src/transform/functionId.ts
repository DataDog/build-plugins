import type * as t from '@babel/types';

import {
    ANONYMOUS_FUNCTION_NAME,
    CLASS_MEMBER_SEPARATOR,
    DUPLICATE_SUFFIX_SEPARATOR,
    FUNCTION_ID_SEPARATOR,
    SCOPE_SEPARATOR,
} from '../constants';

import type { BabelPath, BabelTypesModule } from './babel-path.types';

export type ParsedFunctionId = {
    // Path of the function's file, relative to the repository root.
    modulePath: string;
    // The function's own name, without the names of its containers and its duplicate suffix.
    name: string;
};

const DUPLICATE_SUFFIX_RX = new RegExp(`${DUPLICATE_SUFFIX_SEPARATOR}\\d+$`);

/**
 * Split a function ID generated by `createFunctionIdGenerator` into its module path and the
 * function's display name. Names can contain the separator (e.g. string keys), so the ID is split
 * at its first occurrence.
 */
export function parseFunctionId(functionId: string): ParsedFunctionId | undefined {
    const separatorIndex = functionId.indexOf(FUNCTION_ID_SEPARATOR);
    if (separatorIndex <= 0) {
        return undefined;
    }

    const modulePath = functionId.slice(0, separatorIndex);
    const qualifiedName = functionId.slice(separatorIndex + FUNCTION_ID_SEPARATOR.length);
    const ownNameStart = qualifiedName.lastIndexOf(SCOPE_SEPARATOR) + SCOPE_SEPARATOR.length;
    const ownName = qualifiedName.slice(ownNameStart);

    return { modulePath, name: ownName.replace(DUPLICATE_SUFFIX_RX, '') };
}

// A function or class that the traversal is in.
type Container = {
    // Qualified name of the nearest named function or class, which prefixes the names inside it.
    name: string | undefined;
    // Whether `name` is the container's own name and the container is a class.
    isNamedClass: boolean;
};

export type FunctionIdGenerator = {
    // Return the ID of a function, and make it the container of the functions inside it.
    enterFunction: (functionPath: BabelPath<t.Function>) => string;
    // Make a class the container of the functions inside it.
    enterClass: (classPath: BabelPath<t.Class>) => void;
    // Leave the function or class entered last.
    exit: () => void;
};

/**
 * Generate the IDs of a module's functions, as `<module path>;<qualified name>`, during a traversal
 * that enters and exits every function and class of the module.
 *
 * The qualified name is the function's own name (`<anonymous>` without one), prefixed by the
 * qualified name of the nearest named function or class around it: `Cart.total` for a direct
 * class member, `doubleAll/<anonymous>` otherwise. Anonymous functions and classes don't prefix
 * the names inside them. Functions whose qualified name is already used in the module get the
 * next free `#<n>` suffix, in traversal order. Line numbers aren't part of the ID, so editing a
 * function leaves the IDs of other functions unchanged.
 */
export function createFunctionIdGenerator(
    modulePath: string,
    typesModule: BabelTypesModule,
): FunctionIdGenerator {
    const containers: Container[] = [];
    const usedNames = new Set<string>();
    // Per qualified name, the first suffix that may be free.
    const nextSuffixes = new Map<string, number>();

    const getContainerName = () => containers[containers.length - 1]?.name;

    const qualify = (ownName: string, isClassMember: boolean) => {
        const container = containers[containers.length - 1];
        if (!container?.name) {
            return ownName;
        }

        const separator =
            container.isNamedClass && isClassMember ? CLASS_MEMBER_SEPARATOR : SCOPE_SEPARATOR;
        return `${container.name}${separator}${ownName}`;
    };

    const getUniqueName = (name: string) => {
        let uniqueName = name;
        let suffix = nextSuffixes.get(name) ?? 1;
        while (usedNames.has(uniqueName)) {
            uniqueName = `${name}${DUPLICATE_SUFFIX_SEPARATOR}${suffix}`;
            suffix++;
        }

        nextSuffixes.set(name, suffix);
        usedNames.add(uniqueName);
        return uniqueName;
    };

    return {
        enterFunction(functionPath) {
            const ownName = getOwnFunctionName(functionPath, typesModule);
            const isClassMember = isDirectClassMember(functionPath, typesModule);
            const qualifiedName = qualify(ownName ?? ANONYMOUS_FUNCTION_NAME, isClassMember);
            const uniqueName = getUniqueName(qualifiedName);
            const containerName = ownName ? uniqueName : getContainerName();

            containers.push({ name: containerName, isNamedClass: false });
            return `${modulePath}${FUNCTION_ID_SEPARATOR}${uniqueName}`;
        },
        enterClass(classPath) {
            const className = getClassName(classPath, typesModule);
            if (!className) {
                const containerName = getContainerName();
                containers.push({ name: containerName, isNamedClass: false });
                return;
            }

            const isClassMember = isDirectClassMember(classPath, typesModule);
            const qualifiedName = qualify(className, isClassMember);
            containers.push({ name: qualifiedName, isNamedClass: true });
        },
        exit() {
            containers.pop();
        },
    };
}

/**
 * Get the name of a function if available
 */
export function getFunctionName(
    functionPath: BabelPath<t.Function>,
    typesModule: BabelTypesModule,
): string | null {
    const node = functionPath.node;

    // Named function declaration: function foo() {}
    if ('id' in node && typesModule.isIdentifier(node.id)) {
        return node.id.name;
    }

    // Object/Class method: { foo() {} } or class { foo() {} }
    if (
        typesModule.isObjectMethod(node) ||
        typesModule.isClassMethod(node) ||
        typesModule.isClassPrivateMethod(node)
    ) {
        return getPropertyLikeName(node.key, typesModule);
    }

    return getAssignedName(functionPath.parent, typesModule);
}

// The function's name, with a marker for getters and setters, which share the name of their property.
function getOwnFunctionName(
    functionPath: BabelPath<t.Function>,
    typesModule: BabelTypesModule,
): string | null {
    const name = getFunctionName(functionPath, typesModule);
    const node = functionPath.node;
    if (
        name &&
        (typesModule.isObjectMethod(node) ||
            typesModule.isClassMethod(node) ||
            typesModule.isClassPrivateMethod(node)) &&
        (node.kind === 'get' || node.kind === 'set')
    ) {
        return `${name}:${node.kind}`;
    }

    return name;
}

function getClassName(classPath: BabelPath<t.Class>, typesModule: BabelTypesModule): string | null {
    const id = classPath.node.id;
    if (id) {
        return id.name;
    }

    return getAssignedName(classPath.parent, typesModule);
}

// Name of a function or class from what it's assigned to.
function getAssignedName(parent: t.Node, typesModule: BabelTypesModule): string | null {
    // Variable declaration: const foo = () => {}
    if (typesModule.isVariableDeclarator(parent) && typesModule.isIdentifier(parent.id)) {
        return parent.id.name;
    }

    // Assignment: foo = () => {} or obj.foo = () => {}
    if (typesModule.isAssignmentExpression(parent)) {
        return getAssignmentTargetName(parent.left, typesModule);
    }

    // Object property: { foo: () => {} }
    if (
        typesModule.isObjectProperty(parent) ||
        typesModule.isClassProperty(parent) ||
        typesModule.isClassPrivateProperty(parent)
    ) {
        return getPropertyLikeName(parent.key, typesModule);
    }

    return null;
}

// Whether a function or class is a method of a class or the value of one of its properties.
function isDirectClassMember(memberPath: BabelPath, typesModule: BabelTypesModule): boolean {
    const { node, parent } = memberPath;
    if (typesModule.isClassMethod(node) || typesModule.isClassPrivateMethod(node)) {
        return true;
    }

    return (
        (typesModule.isClassProperty(parent) || typesModule.isClassPrivateProperty(parent)) &&
        parent.value === node
    );
}

function getAssignmentTargetName(
    target: t.LVal | t.OptionalMemberExpression,
    typesModule: BabelTypesModule,
): string | null {
    if (typesModule.isIdentifier(target)) {
        return target.name;
    }

    if (typesModule.isMemberExpression(target) || typesModule.isOptionalMemberExpression(target)) {
        const objectName = getMemberObjectName(target.object, typesModule);
        const propertyName = getMemberPropertyName(target.property, target.computed, typesModule);

        if (objectName && propertyName) {
            return `${objectName}.${propertyName}`;
        }
    }

    return null;
}

function getMemberObjectName(
    target: t.Expression | t.Super,
    typesModule: BabelTypesModule,
): string | null {
    if (typesModule.isIdentifier(target)) {
        return target.name;
    }

    if (typesModule.isThisExpression(target)) {
        return 'this';
    }

    if (typesModule.isMemberExpression(target) || typesModule.isOptionalMemberExpression(target)) {
        const parentObjectName = getMemberObjectName(target.object, typesModule);
        const propertyName = getMemberPropertyName(target.property, target.computed, typesModule);

        if (parentObjectName && propertyName) {
            return `${parentObjectName}.${propertyName}`;
        }
    }

    return null;
}

function getMemberPropertyName(
    property: t.Expression | t.PrivateName,
    isComputed: boolean,
    typesModule: BabelTypesModule,
): string | null {
    if (typesModule.isPrivateName(property) && typesModule.isIdentifier(property.id)) {
        return `#${property.id.name}`;
    }

    if (isComputed) {
        return null;
    }

    if (typesModule.isIdentifier(property)) {
        return property.name;
    }

    return null;
}

function getPropertyLikeName(
    key: t.Expression | t.PrivateName | t.Identifier,
    typesModule: BabelTypesModule,
): string | null {
    if (typesModule.isIdentifier(key)) {
        return key.name;
    }

    if (
        typesModule.isStringLiteral(key) ||
        typesModule.isNumericLiteral(key) ||
        typesModule.isBigIntLiteral(key)
    ) {
        return String(key.value);
    }

    if (typesModule.isPrivateName(key) && typesModule.isIdentifier(key.id)) {
        return `#${key.id.name}`;
    }

    return null;
}
